// Pulls the pieces of the Aura Blueprint DS bundle this app uses into src/ds/.
// Run from the app root: node scripts/extract-ds.mjs
import { readFileSync, writeFileSync, mkdirSync, copyFileSync } from 'node:fs';

const DS = '../project/_ds/aura-blueprint-design-system-def12da2-361d-420f-81ef-efb347ccf23a';
const src = readFileSync(`${DS}/_ds_bundle.js`, 'utf8');
const lines = src.split('\n');

const ICONS = [
  'Shield', 'ChevronLeft', 'ChevronRight', 'Checkmark', 'Play', 'User', 'Plus', 'Info', 'ArrowRight', 'CallMissed',
  'Lock', 'Message', 'Mail', 'Chat', 'Comment', 'Cash', 'CallShield', 'Pause', 'Search3', 'CheckSquareOffset',
  'Medal', 'Exclamation',
];

// icon-data.js is a plain object literal; evaluate just that block.
const start = src.indexOf('const iconData = {');
const end = src.indexOf('};', start) + 2;
const iconData = new Function(src.slice(start, end) + '\nreturn iconData;')();
const subset = {};
for (const n of ICONS) {
  if (!iconData[n]) throw new Error(`Icon missing from DS bundle: ${n}`);
  subset[n] = iconData[n];
}
mkdirSync('src/ds', { recursive: true });
writeFileSync('src/ds/iconData.ts',
  '// Generated by scripts/extract-ds.mjs from the Aura Blueprint DS bundle. Do not edit.\n' +
  `export const iconData = ${JSON.stringify(subset, null, 2)} as const;\n` +
  'export type IconName = keyof typeof iconData;\n');

// Illustrations: slice each module body between its header comment and its scope export.
const slice = (name) => {
  const a = lines.findIndex(l => l === `// assets/illustrations/${name}.jsx`);
  const b = lines.findIndex(l => l === `Object.assign(__ds_scope, { ${name} });`);
  if (a < 0 || b < 0) throw new Error(`Illustration not found: ${name}`);
  // drop the "// path" and "try { (() => {" lines
  return lines.slice(a + 2, b).join('\n');
};
writeFileSync('src/ds/illustrations.js',
  '// Generated by scripts/extract-ds.mjs from the Aura Blueprint DS bundle. Do not edit.\n' +
  "import React from 'react';\n\n" +
  slice('ShieldBlocked') + '\n\n' +
  slice('CallProtection').replace('__ds_scope.ShieldBlocked', 'ShieldBlocked') + '\n\n' +
  'export { ShieldBlocked, CallProtection };\n');

// Token CSS the prototype links.
mkdirSync('src/ds/tokens', { recursive: true });
for (const f of ['fonts', 'colors', 'typography', 'effects']) copyFileSync(`${DS}/tokens/${f}.css`, `src/ds/tokens/${f}.css`);
console.log(`Extracted ${ICONS.length} icons, 2 illustrations, 4 token files.`);
